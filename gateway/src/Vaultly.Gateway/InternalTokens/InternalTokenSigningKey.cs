using System.Security.Cryptography;

using Microsoft.Extensions.Options;
using Microsoft.IdentityModel.Tokens;

namespace Vaultly.Gateway.InternalTokens;

/// <summary>
/// The gateway's RSA key: signs internal tokens and is published, public part only, at <c>/.well-known/jwks.json</c>.
/// </summary>
public sealed class InternalTokenSigningKey
{
    public InternalTokenSigningKey(string privateKeyPem)
    {
        var rsa = RSA.Create();
        try
        {
            rsa.ImportFromPem(privateKeyPem);
        }
        catch (Exception exception) when (exception is CryptographicException or ArgumentException)
        {
            rsa.Dispose();
            throw new InvalidOperationException("The internal token signing key is not an RSA private key in PEM format.", exception);
        }

        var publicKey = JsonWebKeyConverter.ConvertFromRSASecurityKey(new RsaSecurityKey(rsa.ExportParameters(false)));
        var keyId = Base64UrlEncoder.Encode(publicKey.ComputeJwkThumbprint());

        Key = new RsaSecurityKey(rsa) { KeyId = keyId };
        PublicJwk = publicKey;
        PublicJwk.Kid = keyId;
        PublicJwk.Use = JsonWebKeyUseNames.Sig;
        PublicJwk.Alg = SecurityAlgorithms.RsaSha256;
    }

    public RsaSecurityKey Key { get; }

    public JsonWebKey PublicJwk { get; }

    public static InternalTokenSigningKey Load(IOptions<InternalTokenOptions> options, IHostEnvironment environment)
    {
        var settings = options.Value;
        if (!string.IsNullOrWhiteSpace(settings.SigningKeyPem))
        {
            return new InternalTokenSigningKey(settings.SigningKeyPem);
        }

        var path = Path.GetFullPath(settings.SigningKeyPemFilePath, environment.ContentRootPath);
        if (!File.Exists(path) && environment.IsDevelopment() && settings.AutoGenerateDevelopmentSigningKey)
        {
            CreateKeyFile(path);
        }

        if (!File.Exists(path))
        {
            throw new InvalidOperationException($"The internal token signing key file '{path}' was not found.");
        }

        return new InternalTokenSigningKey(File.ReadAllText(path));
    }

    private static void CreateKeyFile(string path)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        using var rsa = RSA.Create(2048);

        try
        {
            using var file = new FileStream(path, FileMode.CreateNew, FileAccess.Write, FileShare.None);
            using var writer = new StreamWriter(file);
            writer.Write(rsa.ExportPkcs8PrivateKeyPem());
        }
        catch (IOException) when (File.Exists(path))
        {
            // Another instance created it first; use that key.
        }
    }
}
