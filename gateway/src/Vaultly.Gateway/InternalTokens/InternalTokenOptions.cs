using System.ComponentModel.DataAnnotations;

namespace Vaultly.Gateway.InternalTokens;

/// <summary>
/// Tokens the gateway issues to services in place of the user's access token (section <c>InternalTokens</c>).
/// </summary>
public sealed class InternalTokenOptions : IValidatableObject
{
    /// <summary>Configuration section name.</summary>
    public const string SectionName = "InternalTokens";

    [Required]
    public string Issuer { get; init; } = string.Empty;

    /// <summary>Upper bound only: a token never outlives the user's access token it was issued for.</summary>
    [Range(1, 15)]
    public int LifetimeMinutes { get; init; } = 5;

    /// <summary>RSA private key in PEM; takes precedence over <see cref="SigningKeyPemFilePath"/>.</summary>
    public string SigningKeyPem { get; init; } = string.Empty;

    /// <summary>File with the RSA private key in PEM, relative to the content root or absolute.</summary>
    public string SigningKeyPemFilePath { get; init; } = string.Empty;

    /// <summary>Development only: create the key file when it is missing.</summary>
    public bool AutoGenerateDevelopmentSigningKey { get; init; }

    public IEnumerable<ValidationResult> Validate(ValidationContext validationContext)
    {
        if (string.IsNullOrWhiteSpace(SigningKeyPem) && string.IsNullOrWhiteSpace(SigningKeyPemFilePath))
        {
            yield return new ValidationResult(
                "Configure InternalTokens:SigningKeyPem or InternalTokens:SigningKeyPemFilePath.",
                [nameof(SigningKeyPem), nameof(SigningKeyPemFilePath)]);
        }
    }
}
