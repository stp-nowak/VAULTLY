// Generates the SPA's API types from the domain services' committed OpenAPI contracts: one plain TypeScript type per
// schema (C# enums become string unions), no paths. Run with `pnpm --filter @vaultly/web api:types`.
import { compile } from 'json-schema-to-typescript';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const webRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = path.resolve(webRoot, '../../..');

const contracts = [
  { contract: 'accounts/openapi/accounts.json', output: 'src/domain/account/api/generated/accounts.ts' },
  { contract: 'transactions/openapi/transactions.json', output: 'src/domain/transaction/api/generated/transactions.ts' },
];

const banner = '// Generated by `pnpm --filter @vaultly/web api:types` from {contract}. Do not edit.';

async function generate({ contract, output }) {
  const { components } = JSON.parse(fs.readFileSync(path.join(repoRoot, contract), 'utf8'));
  // OpenAPI 3.1 schemas are JSON Schema; only the references need to point at $defs.
  const definitions = JSON.parse(JSON.stringify(components.schemas).replaceAll('#/components/schemas/', '#/$defs/'));
  const source = await compile({ $defs: definitions, additionalProperties: false, type: 'object' }, 'Contract', {
    additionalProperties: false,
    bannerComment: banner.replace('{contract}', contract),
    format: true,
    style: { singleQuote: true },
    unreachableDefinitions: true,
  });
  const types = source
    .replace(/\/\*\*\n \* This interface was referenced by `Contract`'s JSON-Schema\n \* via the `definition` "\w+"\.\n \*\/\n/g, '')
    .replace(/export interface Contract \{\}\n/, '')
    .replace(/\n{3,}/g, '\n\n')
    .replace(/\}\nexport /g, '}\n\nexport ');

  fs.mkdirSync(path.dirname(path.join(webRoot, output)), { recursive: true });
  fs.writeFileSync(path.join(webRoot, output), types);
  console.log(`${contract} → ${output}`);
}

for (const target of contracts) {
  await generate(target);
}
