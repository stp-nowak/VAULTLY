namespace Vaultly.Identity.Application.Options;

public sealed class IdentityOptions
{
    public string Issuer { get; set; } = string.Empty;
    public string Audience { get; set; } = string.Empty;

    /// <summary>Public URL of this service (discovery document, endpoints).</summary>
    public string PublicBaseUrl { get; set; } = string.Empty;

    /// <summary>
    /// Where the separately hosted login UI (auth/web) is reachable in the browser. Empty = same origin as
    /// <see cref="PublicBaseUrl"/> (a reverse proxy routes UI and API paths); in development the Vite dev server
    /// (e.g. http://localhost:5174).
    /// </summary>
    public string LoginUiBaseUrl { get; set; } = string.Empty;

    /// <summary>Client applications allowed to request sign-ins.</summary>
    public List<OAuthClientOptions> Clients { get; set; } = [];

    public string JwtPrivateKeyPemFilePath { get; set; } = string.Empty;
    public bool AutoGenerateDevelopmentJwtPrivateKey { get; set; }
    public string JwtPrivateKeyPem { get; set; } = string.Empty;
    public int AccessTokenTtlMinutes { get; set; } = 15;
    public int RefreshTokenTtlDays { get; set; } = 30;
    public int AuthCodeTtlMinutes { get; set; } = 2;
    public int OAuthStateTtlMinutes { get; set; } = 10;

    /// <summary>How long a started sign-in may take before the user has to start again from the app.</summary>
    public int AuthorizationRequestTtlMinutes { get; set; } = 10;

    /// <summary>Maximum lifetime of the single sign-on session (cookie on the auth domain).</summary>
    public int SsoSessionTtlHours { get; set; } = 12;

    /// <summary>The first admin, set up at startup while the service has no admin at all.</summary>
    public BootstrapAdminOptions BootstrapAdmin { get; set; } = new();

    /// <summary>
    /// Base URL of the login UI, falling back to this service's public URL.
    /// </summary>
    public string ResolveLoginUiBaseUrl()
        => (string.IsNullOrWhiteSpace(LoginUiBaseUrl) ? PublicBaseUrl : LoginUiBaseUrl).TrimEnd('/');

    /// <summary>The admin console, part of the login UI.</summary>
    public string ResolveConsoleUrl() => $"{ResolveLoginUiBaseUrl()}/admin";
}

/// <summary>
/// The first admin. While no admin exists, startup makes the user with this email an admin, creating the user when
/// needed; the person then signs in with a provider that has verified this email. Ignored once any admin exists.
/// </summary>
public sealed class BootstrapAdminOptions
{
    public string Email { get; set; } = string.Empty;
}

/// <summary>
/// A registered OAuth client (confidential: authenticates with a secret at the token endpoint).
/// </summary>
public sealed class OAuthClientOptions
{
    public string ClientId { get; set; } = string.Empty;

    /// <summary>Client secret. Provide it through environment/secret store, never commit real values.</summary>
    public string ClientSecret { get; set; } = string.Empty;

    /// <summary>Name shown on the login page ("Sign in to …").</summary>
    public string DisplayName { get; set; } = string.Empty;

    /// <summary>Allowed redirect URIs: exact absolute URIs or prefixes ending with <c>/*</c>.</summary>
    public List<string> RedirectUris { get; set; } = [];

    /// <summary>Allowed post-logout redirect URIs, same matching rules as <see cref="RedirectUris"/>.</summary>
    public List<string> PostLogoutRedirectUris { get; set; } = [];
}
